"""builder.py - Phase 8: `set_company_up(mode="text"|"gui")`.

Two genuinely different-sized builds under one name, as the roadmap frames it.

**Text/schema mode** (this file, and the smaller half): a company builder
shaped so an *AI* can call it. The whole design constraint is that the calling
model must be able to see what its options are and fill them in correctly, so:

- The schema is **generated by `core.ToolRegistry`** from the type hints and
  docstring of `set_up_company`, not hand-written in a parallel format. That
  was the explicit instruction, and it has a real payoff: the tool an agent
  calls and the schema it reads are the same function, so they cannot drift.
- Because `ToolRegistry`'s auto-schema maps flat scalars, `set_up_company`
  takes **flat scalar parameters** - names, an org-template name, a size, a
  budget - plus one optional `employees_json` escape hatch for org shapes no
  template covers. A nested-object schema would have needed a second schema
  generator, which is the thing this phase was told not to build.
- `company_options()` returns the valid names for every preset kind straight
  from Phase 5's `PresetBundle.names()`. This is why text mode depends on
  Phase 5 existing: a schema that says `template: str` is useless to a model,
  while one whose description carries the actual template names is usable.

**GUI mode**: a real interactive node-graph editor, which is a small web app
rather than a Python function. It lives in `gui.py`; `set_company_up(
mode="gui")` dispatches to it. See that module for its own scope notes.

What text mode deliberately does not do: it builds and returns a `Company`,
it does not run anything. Building is cheap and reversible; running spends
money. An AI that can build a company in one tool call and start it in the
same call is one hallucinated argument away from a bill, so the caller has to
take the second step themselves.
"""

import json
from dataclasses import dataclass, field
from typing import Any, Callable, Dict, List, Optional, Sequence

from .company import Company, EscalationDecision, EscalationEvent
from .core import ToolRegistry
from .presets import ORG_TEMPLATES, PALETTES, PERSONALITIES, SKILLS, TASK_SIZES, default_bundle
from .router import RoleRank

# A rank -> model_map entry used when the caller supplies no model_map at all.
# Everything routes to Ollama locally, which is the only provider that needs no
# API key - so a company built by an AI with no configuration cannot
# accidentally start spending money. Override with model_map= for real use.
DEFAULT_MODEL_MAP: Dict[str, Dict[str, Any]] = {
    rank: {"provider": "ollama", "model": "llama3.1:8b", "mode": "auto"}
    for rank in RoleRank.ORDER
}


def default_on_escalation(event: EscalationEvent) -> EscalationDecision:
    """The escalation callback used when the caller supplies none.

    Declines. That is the deliberate choice, matching the 0-means-always-ask
    defaults Phases 0-3 set for both emergency reserves: a company built
    programmatically (possibly by another AI) has no human attached to it, and
    "no human available" must mean "stop", never "approve yourself".
    """
    return EscalationDecision(
        approve=False,
        note="No on_escalation handler was configured for this company, so the request was declined.",
    )


