@dataclass
class EmployeeSpec:
    """One employee in a hand-written company spec."""

    name: str
    rank: str = RoleRank.SENIOR
    reports_to: Optional[str] = None
    skills: Sequence[str] = ()
    personality: Optional[str] = None
    effort: Optional[str] = None
    specialty: Optional[str] = None
    importance: float = 0.5
    provider: Optional[str] = None
    model: Optional[str] = None
    mode: Optional[str] = None

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "EmployeeSpec":
        if not isinstance(data, dict):
            raise ValueError(f"each employee must be an object, got {type(data).__name__}")
        if not data.get("name"):
            raise ValueError("each employee needs a 'name'")
        known = {f for f in cls.__dataclass_fields__}  # noqa: SLF001 - dataclass API
        unknown = set(data) - known
        if unknown:
            raise ValueError(f"employee {data['name']!r} has unknown field(s): {', '.join(sorted(unknown))}")
        return cls(**data)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "name": self.name, "rank": self.rank, "reports_to": self.reports_to,
            "skills": list(self.skills), "personality": self.personality,
            "effort": self.effort, "specialty": self.specialty, "importance": self.importance,
            "provider": self.provider, "model": self.model, "mode": self.mode,
        }


@dataclass
class CompanySpec:
    """Everything needed to build a Company, as plain data.

    This is the format `gui.py` saves and loads too, so the GUI and the text
    tool produce the same artifact and either can consume the other's output.
    """

    name: str = "New Company"
    template: Optional[str] = None
    size: str = "small"
    employees: List[EmployeeSpec] = field(default_factory=list)
    palette: str = "dataviz"
    total_token_budget: Optional[int] = None
    emergency_budget_tokens: int = 0
    emergency_iteration_reserve: int = 0
    review_mode: str = "critique"
    max_review_rounds: int = 1
    notes: str = ""

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "CompanySpec":
        data = dict(data or {})
        employees = [EmployeeSpec.from_dict(e) for e in data.pop("employees", []) or []]
        known = {f for f in cls.__dataclass_fields__}  # noqa: SLF001
        unknown = set(data) - known
        if unknown:
            raise ValueError(f"unknown company field(s): {', '.join(sorted(unknown))}")
        return cls(employees=employees, **data)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "name": self.name, "template": self.template, "size": self.size,
            "employees": [e.to_dict() for e in self.employees], "palette": self.palette,
            "total_token_budget": self.total_token_budget,
            "emergency_budget_tokens": self.emergency_budget_tokens,
            "emergency_iteration_reserve": self.emergency_iteration_reserve,
            "review_mode": self.review_mode, "max_review_rounds": self.max_review_rounds,
            "notes": self.notes,
        }

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self.to_dict(), indent=indent)

    @classmethod
    def from_json(cls, text: str) -> "CompanySpec":
        return cls.from_dict(json.loads(text))

    def validate(self, bundle: Optional[Any] = None) -> List[str]:
        """Returns a list of human-readable problems - empty means valid.

        Returns rather than raises because the caller here is often a model
        filling in a schema, and "here are the four things wrong with what you
        sent" is a far more useful reply than a traceback on the first one.
        """
        bundle = bundle or default_bundle()
        problems: List[str] = []

        if not self.name:
            problems.append("company needs a name")
        if self.size not in TASK_SIZES:
            problems.append(f"size {self.size!r} is not one of: {', '.join(TASK_SIZES)}")
        if self.template and self.template not in bundle.org_templates:
            problems.append(
                f"unknown template {self.template!r}. Available: {', '.join(bundle.org_templates.names())}"
            )
        if self.palette and self.palette not in bundle.palettes:
            problems.append(
                f"unknown palette {self.palette!r}. Available: {', '.join(bundle.palettes.names())}"
            )
        if self.review_mode not in ("critique", "append", "off"):
            problems.append(f"review_mode {self.review_mode!r} is not one of: critique, append, off")
        if not self.template and not self.employees:
            problems.append("give either a template or at least one employee")

        names = [e.name for e in self.employees]
        for duplicate in {n for n in names if names.count(n) > 1}:
            problems.append(f"duplicate employee name {duplicate!r} - names must be unique")

        # A hand-written employee may report to someone the *template* creates,
        # since a spec is allowed to extend a template rather than replace it.
        # Those names don't exist until build time, so derive them here.
        known_names = set(names)
        if self.template and self.template in bundle.org_templates and self.size in TASK_SIZES:
            template = bundle.org_templates.get(self.template)
            for role in template.roles_for(self.size):
                count = role.count_for(self.size)
                for index in range(count):
                    suffix = f" {index + 1}" if count > 1 else ""
                    known_names.add(f"{role.display_title()}{suffix}")

        for employee in self.employees:
            if employee.rank not in RoleRank.ORDER:
                problems.append(
                    f"{employee.name}: unknown rank {employee.rank!r}. "
                    f"Available: {', '.join(RoleRank.ORDER)}"
                )
            if employee.reports_to and employee.reports_to not in known_names:
                problems.append(
                    f"{employee.name}: reports_to {employee.reports_to!r}, who is not in this company"
                )
            for skill in employee.skills:
                if skill not in bundle.skills:
                    problems.append(
                        f"{employee.name}: unknown skill {skill!r}. "
                        f"Available: {', '.join(bundle.skills.names())}"
                    )
            if employee.personality and employee.personality not in bundle.personalities:
                problems.append(
                    f"{employee.name}: unknown personality {employee.personality!r}. "
                    f"Available: {', '.join(bundle.personalities.names())}"
                )

        # Reporting cycles - the same check org templates get, since a
        # hand-written spec can describe one just as easily.
        by_name = {e.name: e for e in self.employees}
        for employee in self.employees:
            seen = {employee.name}
            cursor = employee.reports_to
            while cursor and cursor in by_name:
                if cursor in seen:
                    problems.append(f"reporting cycle involving {cursor!r}")
                    break
                seen.add(cursor)
                cursor = by_name[cursor].reports_to

        return problems


