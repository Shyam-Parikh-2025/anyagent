def set_company_up(mode: str = "text", **kwargs: Any) -> Any:
    """Build a company. Two genuinely different modes under one name.

    mode="text" - build from arguments (or a spec) and return a BuildResult.
        This is the AI-callable path; `set_up_company` is the same thing
        wrapped as a tool returning JSON.
    mode="gui" - open the interactive node-graph editor (see gui.py) and
        return whatever the user built there.

    Text-mode arguments are the fields of CompanySpec, plus the runtime
    arguments of build_company (model_map, on_escalation, model_policy,
    presets, log_compaction). Pass `spec=` to supply a CompanySpec or dict
    directly instead of field by field.
    """
    mode = (mode or "text").strip().lower()
    if mode == "gui":
        from .gui import launch_gui

        return launch_gui(**kwargs)
    if mode != "text":
        raise ValueError(f"unknown mode {mode!r} - use 'text' or 'gui'")

    runtime_keys = ("model_map", "on_escalation", "model_policy", "presets", "log_compaction")
    runtime = {k: kwargs.pop(k) for k in runtime_keys if k in kwargs}

    spec_arg = kwargs.pop("spec", None)
    if spec_arg is not None:
        spec = spec_arg if isinstance(spec_arg, CompanySpec) else CompanySpec.from_dict(spec_arg)
    else:
        employees_json = kwargs.pop("employees_json", "") or ""
        employees: List[Dict[str, Any]] = []
        if str(employees_json).strip():
            try:
                parsed = json.loads(employees_json)
            except json.JSONDecodeError as e:
                return BuildResult(problems=[f"employees_json is not valid JSON: {e}"])
            if not isinstance(parsed, list):
                return BuildResult(problems=["employees_json must be a JSON array of employee objects"])
            employees = parsed

        # An empty-string template means "none", and a 0 budget means "no
        # ceiling" - both because ToolRegistry's flat scalar schema has no way
        # to express null, so the sentinel has to live here.
        kwargs["template"] = kwargs.get("template") or None
        budget = kwargs.pop("total_token_budget", None)
        kwargs["total_token_budget"] = budget if budget else None
        try:
            spec = CompanySpec.from_dict({**kwargs, "employees": employees})
        except (ValueError, TypeError) as e:
            return BuildResult(problems=[str(e)])

    return build_company(spec, **runtime)


