@dataclass
class BuildResult:
    """The structured "what got built" an AI caller needs back.

    `company` is the live object; everything else is JSON-serializable so the
    whole thing can be handed straight back through a tool result.
    """

    company: Optional[Company] = None
    spec: Optional[CompanySpec] = None
    problems: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return self.company is not None and not self.problems

    def to_dict(self) -> Dict[str, Any]:
        out: Dict[str, Any] = {
            "ok": self.ok,
            "problems": list(self.problems),
            "warnings": list(self.warnings),
        }
        if self.spec is not None:
            out["spec"] = self.spec.to_dict()
        if self.company is not None:
            out["company"] = self.company.name
            out["employees"] = [
                {
                    "name": e.name, "rank": e.rank,
                    "reports_to": e.reports_to.name if e.reports_to else None,
                    "skills": [getattr(s, "name", s) for s in e.skills],
                    "personality": getattr(e.personality, "name", e.personality),
                    "effort": e.effort, "specialty": e.specialty,
                    "provider": e.agent.provider, "model": e.agent.model,
                }
                for e in self.company.employees.values()
            ]
            out["teams"] = [
                {"name": t.name, "lead": t.lead.name,
                 "reviewer": t.reviewer.name if t.reviewer else None,
                 "members": [m.name for m in t.members],
                 "review_mode": t.review_mode}
                for t in self.company.teams
            ]
            out["org_chart"] = self.company.render_org_chart(fmt="ascii")
        return out


def build_company(
    spec: CompanySpec,
    model_map: Optional[Dict[str, Dict[str, Any]]] = None,
    on_escalation: Optional[Callable[[EscalationEvent], EscalationDecision]] = None,
    model_policy: Optional[Any] = None,
    presets: Optional[Any] = None,
    log_compaction: Optional[Any] = None,
) -> BuildResult:
    """Turn a CompanySpec into a live Company.

    Validation runs first and a failing spec returns a BuildResult with
    `problems` and no company - nothing is half-built. Runtime concerns
    (model_map, on_escalation, model_policy, presets, log_compaction) are
    arguments rather than spec fields on purpose: they are callables and
    policy objects, they don't serialize, and putting them in the spec would
    mean an AI-authored JSON blob could name a provider and an API key. The
    spec describes the *org*; the caller supplies the *runtime*.
    """
    presets = presets or default_bundle()
    problems = spec.validate(presets)
    if problems:
        return BuildResult(spec=spec, problems=problems)

    warnings: List[str] = []
    if model_map is None:
        model_map = DEFAULT_MODEL_MAP
        warnings.append(
            "no model_map given - every rank defaults to a local Ollama model, so this "
            "company cannot spend money until you configure one"
        )
    if on_escalation is None:
        on_escalation = default_on_escalation
        warnings.append(
            "no on_escalation handler given - escalations will be declined automatically"
        )
    if spec.total_token_budget is None:
        warnings.append(
            "no total_token_budget set - this company has no spend ceiling (see Phase 3)"
        )

    company = Company(
        name=spec.name,
        model_map=model_map,
        on_escalation=on_escalation,
        total_token_budget=spec.total_token_budget,
        emergency_budget_tokens=spec.emergency_budget_tokens,
        emergency_iteration_reserve=spec.emergency_iteration_reserve,
        model_policy=model_policy,
        presets=presets,
        log_compaction=log_compaction,
    )

    if spec.template:
        company.build_from_template(
            spec.template, size=spec.size,
            review_mode=spec.review_mode, max_review_rounds=spec.max_review_rounds,
        )

    # Hand-written employees are hired after any template, parents first, so
    # a spec can extend a template as well as replace it.
    pending = list(spec.employees)
    guard = len(pending) + 1
    while pending and guard:
        guard -= 1
        for employee in list(pending):
            manager = None
            if employee.reports_to:
                manager = company.employees.get(employee.reports_to)
                if manager is None:
                    continue  # manager not hired yet - try again next pass
            company.hire(
                name=employee.name, rank=employee.rank, reports_to=manager,
                skills=employee.skills, personality=employee.personality,
                effort=employee.effort, specialty=employee.specialty,
                importance=employee.importance, provider=employee.provider,
                model=employee.model, mode=employee.mode,
            )
            pending.remove(employee)
    if pending:  # validate() rules this out; belt and braces
        return BuildResult(
            spec=spec,
            problems=[f"could not resolve reporting lines for: {', '.join(e.name for e in pending)}"],
        )

    company._log("company_built", employee=None, template=spec.template, size=spec.size,
                 headcount=len(company.employees))
    return BuildResult(company=company, spec=spec, warnings=warnings)


