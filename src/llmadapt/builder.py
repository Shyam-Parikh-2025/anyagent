def company_options(bundle: Optional[Any] = None) -> Dict[str, List[str]]:
    """The valid names for everything `set_up_company` accepts.

    Straight from Phase 5's registries - this is the dependency that made text
    mode wait for Phase 5. Give this to a model alongside the schema; a schema
    saying `template: str` tells it nothing, while the actual list of template
    names makes the tool usable in one shot.
    """
    bundle = bundle or default_bundle()
    options = bundle.names()
    options["ranks"] = list(RoleRank.ORDER)
    options["sizes"] = list(TASK_SIZES)
    options["review_modes"] = ["critique", "append", "off"]
    return options


def set_up_company(
    name: str,
    template: str = "",
    size: str = "small",
    palette: str = "dataviz",
    total_token_budget: int = 0,
    review_mode: str = "critique",
    max_review_rounds: int = 1,
    employees_json: str = "",
    notes: str = "",
) -> str:
    """Create a multi-agent company and report what was built.

    Builds the org only - it does not run any task, so calling this costs
    nothing. Call company_options() first to see the valid names for template,
    skills, personalities and palettes.

    name: what to call the company.
    template: a ready-made org shape by name, e.g. 'small-coding-team'. Leave
        empty to describe the employees yourself in employees_json.
    size: 'small', 'medium' or 'large' - how far to scale the template's
        worker roles. Ignored when no template is given.
    palette: the org-chart colour scheme by name, e.g. 'dataviz'.
    total_token_budget: a hard ceiling on total tokens this company may spend.
        0 means no ceiling, which is the riskier choice.
    review_mode: 'critique' (reviewer can send work back), 'append' (reviewer
        gives a second opinion) or 'off' (no review).
    max_review_rounds: how many times a reviewer may send work back.
    employees_json: a JSON array of employees, for org shapes no template
        covers. Each entry looks like {"name": "Ada", "rank": "SENIOR",
        "reports_to": "Grace", "skills": ["python"], "personality": "concise",
        "effort": "balanced", "importance": 0.5}. Can be combined with a
        template to extend it.
    notes: free text stored with the spec, for whoever reads it later.

    Returns a JSON report: whether it worked, the employees and teams created,
    an ASCII org chart, and any problems or warnings.
    """
    result = set_company_up(
        mode="text", name=name, template=template, size=size, palette=palette,
        total_token_budget=total_token_budget, review_mode=review_mode,
        max_review_rounds=max_review_rounds, employees_json=employees_json, notes=notes,
    )
    # to_dict() already carries only the company's *name*, never the live
    # object - a tool result has to survive json.dumps.
    return json.dumps(result.to_dict(), indent=2, default=str)


def company_setup_schema(bundle: Optional[Any] = None) -> Dict[str, Any]:
    """The tool schema for `set_up_company`, generated by `ToolRegistry`.

    Deliberately generated rather than written: `ToolRegistry.register()`
    already derives a schema from type hints plus the docstring, so the tool
    an agent calls and the schema it reads come from the same function and
    cannot drift apart. This adds one thing on top - the live preset names
    from Phase 5's registries appended to the relevant parameter descriptions,
    which is the difference between a schema a model can guess at and one it
    can fill in correctly.
    """
    registry = ToolRegistry()
    registry.register(set_up_company)
    schema = json.loads(json.dumps(registry.schemas["set_up_company"]))  # deep copy

    options = company_options(bundle)
    enrichment = {
        "template": options["org_templates"],
        "size": options["sizes"],
        "palette": options["palettes"],
        "review_mode": options["review_modes"],
    }
    properties = schema.get("parameters", {}).get("properties", {})
    for param, values in enrichment.items():
        if param in properties:
            properties[param]["enum"] = list(values)
            properties[param]["description"] = (
                f"{properties[param].get('description', '')} One of: {', '.join(values)}."
            ).strip()
    if "employees_json" in properties:
        properties["employees_json"]["description"] += (
            f" Valid ranks: {', '.join(options['ranks'])}."
            f" Valid skills: {', '.join(options['skills'])}."
            f" Valid personalities: {', '.join(options['personalities'])}."
        )
    return schema


def register_company_builder(agent: Any) -> Any:
    """Give an Agent the ability to build companies.

    One line for the common case: `register_company_builder(my_agent)` and the
    agent can now call set_up_company through the ordinary tool-calling loop,
    with the enriched schema.
    """
    agent.add_tool(set_up_company, schema=company_setup_schema())
    return agent


